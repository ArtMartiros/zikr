/* Кибла — это начальный азимут ортодромии, а не «примерно на юг». Проверка
   держит именно это: азимуты сверены с общеизвестными значениями для
   городов, где кибла нанесена на пол мечети. Ошибка в знаке или в порядке
   аргументов atan2 такую сверку не переживёт. */

import { qiblaBearing, qiblaDistance, compassSide } from "../src/lib/qibla.mjs";
import { ok, near, section, done } from "./lib.mjs";

section("Известные азимуты");
const KNOWN = [
  ["Москва", 55.7558, 37.6173, 176.4, 3822],
  ["Лондон", 51.5074, -0.1278, 119.0, 4794],
  ["Стамбул", 41.0082, 28.9784, 151.6, 2405],
  ["Нью-Йорк", 40.7128, -74.006, 58.5, 10306],
  ["Джакарта", -6.2088, 106.8456, 295.2, 7920],
  ["Казань", 55.7963, 49.1064, 195.1, 3899],
];
for (const [name, lat, lon, bearing, km] of KNOWN) {
  near(qiblaBearing(lat, lon), bearing, 0.6, `азимут из «${name}»`);
  near(qiblaDistance(lat, lon), km, 12, `расстояние из «${name}»`);
}

section("Свойства");
ok(qiblaDistance(21.4225, 39.8262) === 0, "в самой Мекке расстояние до Каабы — ноль");

// Прямо к северу от Каабы кибла смотрит строго на юг, прямо к югу — на север
near(qiblaBearing(40, 39.8262), 180, 0.01, "точка севернее Каабы");
near(qiblaBearing(0, 39.8262), 0, 0.01, "точка южнее Каабы");

for (let lat = -60; lat <= 70; lat += 10) {
  for (let lon = -180; lon < 180; lon += 15) {
    const b = qiblaBearing(lat, lon);
    if (!ok(Number.isFinite(b) && b >= 0 && b < 360, `азимут в пределах круга для ${lat}, ${lon}`)) break;
  }
}

section("Стороны света");
ok(compassSide(0) === "С", "ноль градусов — север");
ok(compassSide(176.4) === "Ю", "кибла из Москвы — юг");
ok(compassSide(295.2) === "СЗ", "кибла из Джакарты — северо-запад");

done("Кибла");
