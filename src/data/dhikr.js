export const DEFAULT_SET = "tasbih";

export function findSet(id, custom) {
  if (custom && custom.id === id) return custom;
  return SETS.find((s) => s.id === id) || SETS[0];
}

/* Сколько всего произнесений в полном круге набора. */
export function setTotal(set) {
  return set.steps.reduce((sum, step) => sum + step.target, 0);
}
